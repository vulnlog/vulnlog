package dev.vulnlog.lib.codec.suppression.dependencycheck

import dev.vulnlog.lib.codec.suppression.SuppressionEncoder
import dev.vulnlog.lib.model.VulnId
import dev.vulnlog.lib.model.suppression.SuppressionEntry
import dev.vulnlog.lib.model.suppression.SuppressionFormat
import dev.vulnlog.lib.model.suppression.SuppressionList
import io.kotest.assertions.throwables.shouldThrow
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldNotContain
import io.kotest.matchers.string.shouldStartWith
import org.w3c.dom.Document
import org.xml.sax.InputSource
import java.io.StringReader
import java.time.LocalDate
import javax.xml.XMLConstants
import javax.xml.parsers.DocumentBuilderFactory
import javax.xml.transform.stream.StreamSource
import javax.xml.validation.SchemaFactory

class DependencyCheckSuppressionEncoderTest :
    FunSpec({

        test("direct encoding rejects unpaired UTF-16 surrogates") {
            listOf(0xD800, 0xDFFF).forEach { codePoint ->
                val list =
                    SuppressionList(
                        SuppressionFormat.DependencyCheck,
                        setOf(SuppressionEntry(VulnId.Cve("CVE-2026-1111"), reason = codePoint.toChar().toString())),
                    )

                shouldThrow<IllegalArgumentException> { DependencyCheckSuppressionEncoder.encode(list) }
            }
        }

        test("schema-valid XML preserves escaped notes, unicode, newlines and optional expiry") {
            val reason = "Reviewed <code> & \"quotes\" 'apostrophe' ]]>\r\nNo injection: </notes><suppress> — 🔒"
            val list =
                SuppressionList(
                    SuppressionFormat.DependencyCheck,
                    setOf(
                        SuppressionEntry(VulnId.Cve("CVE-2026-1111"), LocalDate.of(2026, 8, 1), reason),
                        SuppressionEntry(VulnId.Cve("CVE-2026-2222")),
                    ),
                )

            val xml = SuppressionEncoder.encode(list)
            validateSchema(xml)
            val document = parse(xml)

            xml shouldStartWith "<!-- Generated by Vulnlog (https://vulnlog.dev). DO NOT EDIT. -->\n"
            document.getElementsByTagName("suppress").length shouldBe 2
            document.getElementsByTagName("notes").length shouldBe 1
            document.getElementsByTagName("notes").item(0).textContent shouldBe reason
            document.getElementsByTagName("cve").item(0).textContent shouldBe "CVE-2026-1111"
            document
                .getElementsByTagName("suppress")
                .item(0)
                .attributes
                .getNamedItem("until")
                .nodeValue shouldBe
                "2026-08-01Z"
            document
                .getElementsByTagName("suppress")
                .item(1)
                .attributes
                .getNamedItem("until") shouldBe null
        }

        test("an empty list remains a schema-valid XML document") {
            val xml = SuppressionEncoder.encode(SuppressionList(SuppressionFormat.DependencyCheck, emptySet()))

            validateSchema(xml)

            parse(xml).getElementsByTagName("suppress").length shouldBe 0
            xml shouldNotContain "until="
        }
    })

private fun validateSchema(xml: String) {
    val factory = SchemaFactory.newInstance(XMLConstants.W3C_XML_SCHEMA_NS_URI)
    factory.setProperty(XMLConstants.ACCESS_EXTERNAL_DTD, "")
    factory.setProperty(XMLConstants.ACCESS_EXTERNAL_SCHEMA, "")
    // Vendored from the schema linked by the Dependency-Check suppression documentation; tests stay offline.
    val resource =
        DependencyCheckSuppressionEncoderTest::class.java.getResource(
            "/suppress/dependency-suppression.1.3.xsd",
        )!!
    factory.newSchema(resource).newValidator().validate(StreamSource(StringReader(xml)))
}

private fun parse(xml: String): Document {
    val factory = DocumentBuilderFactory.newInstance()
    factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true)
    return factory.newDocumentBuilder().parse(InputSource(StringReader(xml)))
}
