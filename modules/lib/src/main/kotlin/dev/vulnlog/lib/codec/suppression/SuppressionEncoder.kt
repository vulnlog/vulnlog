package dev.vulnlog.lib.codec.suppression

import dev.vulnlog.lib.codec.suppression.cargoaudit.CargoAuditSuppressionEncoder
import dev.vulnlog.lib.codec.suppression.dependencycheck.DependencyCheckSuppressionEncoder
import dev.vulnlog.lib.codec.suppression.generic.GenericSuppressionEncoder
import dev.vulnlog.lib.codec.suppression.snyk.SnykSuppressionEncoder
import dev.vulnlog.lib.codec.suppression.trivy.TrivySuppressionEncoder
import dev.vulnlog.lib.model.suppression.SuppressionEncodingProblem
import dev.vulnlog.lib.model.suppression.SuppressionFormat
import dev.vulnlog.lib.model.suppression.SuppressionList

private const val GENERATED_BY = "Generated by Vulnlog (https://vulnlog.dev). DO NOT EDIT."

object SuppressionEncoder {
    /** Validate all entries before a driver writes any output. */
    fun validate(list: SuppressionList): List<SuppressionEncodingProblem> =
        when (list.format) {
            SuppressionFormat.DependencyCheck -> DependencyCheckSuppressionEncoder.validate(list)
            else -> emptyList()
        }

    /** JSON has no comments, so the generic file goes without the header. */
    fun encode(list: SuppressionList): String =
        when (list.format) {
            is SuppressionFormat.Generic -> GenericSuppressionEncoder.encode(list)
            SuppressionFormat.Trivy -> "# $GENERATED_BY\n" + TrivySuppressionEncoder.encode(list)
            SuppressionFormat.Snyk -> "# $GENERATED_BY\n" + SnykSuppressionEncoder.encode(list)
            SuppressionFormat.CargoAudit -> "# $GENERATED_BY\n" + CargoAuditSuppressionEncoder.encode(list)
            SuppressionFormat.DependencyCheck ->
                "<!-- $GENERATED_BY -->\n" +
                    DependencyCheckSuppressionEncoder.encode(list)
        }
}
