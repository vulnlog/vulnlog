package dev.vulnlog.lib.codec.suppression

import dev.vulnlog.lib.codec.suppression.cargoaudit.CargoAuditSuppressionWriter
import dev.vulnlog.lib.codec.suppression.generic.GenericSuppressionWriter
import dev.vulnlog.lib.codec.suppression.snyk.SnykSuppressionWriter
import dev.vulnlog.lib.codec.suppression.trivy.TrivySuppressionWriter
import dev.vulnlog.lib.model.suppress.SuppressionOutput

data class SuppressionFile(
    val fileName: String,
    val content: String,
)

private const val GENERATED_BY = "# Generated by Vulnlog (https://vulnlog.dev). DO NOT EDIT.\n"

object SuppressionWriter {
    fun writeSuppressionOutput(output: SuppressionOutput): SuppressionFile =
        when (output) {
            is SuppressionOutput.GenericSuppression ->
                SuppressionFile(
                    fileName = output.fileName,
                    content = GenericSuppressionWriter.write(output),
                )

            is SuppressionOutput.TrivySuppression ->
                SuppressionFile(
                    fileName = output.fileName,
                    content = GENERATED_BY + TrivySuppressionWriter.write(output),
                )

            is SuppressionOutput.SnykSuppression ->
                SuppressionFile(
                    fileName = output.fileName,
                    content = GENERATED_BY + SnykSuppressionWriter.write(output),
                )

            is SuppressionOutput.CargoAuditSuppression ->
                SuppressionFile(
                    fileName = output.fileName,
                    content = GENERATED_BY + CargoAuditSuppressionWriter.write(output),
                )
        }
}
